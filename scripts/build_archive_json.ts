import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { listPastArchiveDocuments, toArchiveRouteIndex } from '../app/lib/archive-document';

export interface ArchiveArtifactPaths {
  publicDir: string;
  indexPath: string;
}

export function renderArchiveRouteIndexModule(documents = listPastArchiveDocuments()): string {
  const entries = toArchiveRouteIndex(documents);
  return `// Generated by scripts/build_archive_json.ts. Do not edit.
import type { ArchiveRouteIndexEntry } from './archive-types';

export const ARCHIVE_ROUTE_INDEX: ArchiveRouteIndexEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

/** Writes past-basho JSON and the small route index the client bundle imports. */
export function writeArchiveArtifacts({ publicDir, indexPath }: ArchiveArtifactPaths): string[] {
  const documents = listPastArchiveDocuments();
  const directory = resolve(publicDir, 'api/v1/archive');
  mkdirSync(directory, { recursive: true });
  const files = documents.map((document) => {
    const filePath = resolve(directory, `${document.monthKey}.json`);
    writeFileSync(filePath, `${JSON.stringify(document)}\n`);
    return filePath;
  });
  writeFileSync(indexPath, renderArchiveRouteIndexModule(documents));
  return files;
}

const isDirectRun = process.argv[1]?.endsWith('build_archive_json.ts') === true;

if (isDirectRun) {
  const root = resolve(new URL('..', import.meta.url).pathname);
  writeArchiveArtifacts({
    publicDir: resolve(root, 'public'),
    indexPath: resolve(root, 'app/lib/archive-route-index.generated.ts'),
  });
}
