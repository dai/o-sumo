export type ImageMeta = {
  primary: string;
  width: number;
  height: number;
  alt: string;
};

export type PageMeta = {
  title: string;
  description: string;
  canonicalUrl: string;
  /** @deprecated Prefer `image.primary`. Retained for backwards compatibility with templates that read this field directly. */
  imageUrl: string;
  image: ImageMeta;
  type: 'website';
  isNotFound?: boolean;
};

const IMAGE_VERSION = '20260913';

const OG_DEFAULT_SHARE = `${SITE_ORIGIN}/images/og-default.jpg?v=${IMAGE_VERSION}`;
const OG_DEFAULT_TWITTER = `${SITE_ORIGIN}/images/og-default-twitter.png?v=${IMAGE_VERSION}`;
const OG_RIKISHI_DEFAULT = `${SITE_ORIGIN}/images/og-rikishi-default.jpg?v=${IMAGE_VERSION}`;
const OG_COMPARE_DEFAULT = `${SITE_ORIGIN}/images/og-compare-default.jpg?v=${IMAGE_VERSION}`;

const DEFAULT_IMAGE: ImageMeta = {
  primary: OG_DEFAULT_SHARE,
  width: 1200,
  height: 630,
  alt: 'o-sumo 大相撲情報サイトのOGP画像',
};

/**
 * Pick the right OGP image for a given canonical path. The Yūgen-toned
 * default set lives under /images/ and is generated by scripts/og-templates/
 * via Playwright screenshot.
 */
function resolveImageMeta(canonicalPath: string): ImageMeta {
  if (canonicalPath === '/compare/' || canonicalPath.startsWith('/compare/')) {
    return {
      primary: OG_COMPARE_DEFAULT,
      width: 1200,
      height: 630,
      alt: 'o-sumo 力士比較ページのOGP画像',
    };
  }
  if (/^\/rikishi\/[^/]+\/$/.test(canonicalPath)) {
    return {
      primary: OG_RIKISHI_DEFAULT,
      width: 1200,
      height: 630,
      alt: 'o-sumo 力士プロフィールページのOGP画像',
    };
  }
  return DEFAULT_IMAGE;
}

const HOME_META = {
  title: 'o-sumo | 大相撲 番付・星取表',
  description: '大相撲の番付・星取表・取組スケジュール・場所結果を網羅したアーカイブ。最新の場所進行中も取組結果をリアルタイムで更新します。',
} as const;

function homeMeta(): PageMeta {
  return pageMeta('/', HOME_META.title, HOME_META.description);
}

function notFoundMeta(): PageMeta {
  const image = DEFAULT_IMAGE;
  return {
    title: '404 ページが見つかりません | o-sumo',
    description: 'お探しのページは見つかりませんでした。o-sumoの最新取組表や番付一覧をご確認ください。',
    canonicalUrl: `${SITE_ORIGIN}/404`,
    imageUrl: image.primary,
    image,
    type: 'website',
    isNotFound: true,
  };
}

function bashoLabel(year: string, month: string): string {
  return `${year}年${Number(month)}月場所`;
}

function pageMeta(pathname: string, title: string, description: string): PageMeta {
  const canonicalPath = normalizeCanonicalPath(pathname);
  const image = resolveImageMeta(canonicalPath);
  return {
    title,
    description,
    canonicalUrl: toCanonicalUrl(canonicalPath),
    imageUrl: image.primary,
    image,
    type: 'website',
  };
}

export function resolvePageMeta(pathname: string): PageMeta {
  const canonicalPath = normalizeCanonicalPath(pathname);

  if (canonicalPath === '/') return homeMeta();

  const fixedPages: Record<string, { title: string; description: string }> = {
    '/archives/': {
      title: '大相撲の場所別アーカイブ | o-sumo',
      description: '大相撲の過去の場所ごとの番付、取組結果、取組予定を閲覧できます。',
    },
    '/rikishi/': {
      title: '力士一覧 | o-sumo',
      description: '大相撲力士のプロフィール、番付、成績を一覧で確認できます。',
    },
    '/my-rikishi/': {
      title: 'マイ力士 | o-sumo',
      description: '気になる力士を端末に保存し、ログインすると端末間で同期できます。',
    },
    '/compare/': {
      title: '力士比較 | o-sumo',
      description: '幕内・十両力士の合口、体格、得意決まり手、通算成績を比較できます。',
    },
    '/gyoji/': { title: '行司名鑑 | o-sumo', description: '大相撲の現役行司の階級とプロフィールを一覧で紹介します。' },
    '/yobidashi/': { title: '呼出名鑑 | o-sumo', description: '大相撲の現役呼出の階級とプロフィールを一覧で紹介します。' },
    '/kimarite/': {
      title: '決まり手一覧 | o-sumo',
      description: '大相撲の決まり手を分類別にわかりやすく紹介します。',
    },
    '/analytics/': {
      title: '大相撲データ分析 | o-sumo',
      description: '大相撲の取組結果、力士、決まり手のデータを分析します。',
    },
    '/about/': {
      title: '当サイトについて・プライバシーポリシー | o-sumo',
      description: 'o-sumoのサイト概要、データ出典、免責事項、プライバシーポリシー、利用規約、運営者情報について。',
    },
    '/privacy/': {
      title: 'プライバシーポリシー | o-sumo',
      description: 'ウェブサイトと MCP サーバーで扱う情報、任意の Google ログイン、保存と削除について説明します。',
    },
    '/terms/': {
      title: '利用規約 | o-sumo',
      description: '縦綱 / o-sumo のウェブサイトと MCP サーバーの利用条件。',
    },
  };
  const fixedPage = fixedPages[canonicalPath];
  if (fixedPage) return pageMeta(canonicalPath, fixedPage.title, fixedPage.description);

  const banzukeMatch = canonicalPath.match(/^\/(\d{4})(\d{2})-banzuke\/$/);
  if (banzukeMatch) {
    const [, year, month] = banzukeMatch;
    if (!getArchiveRouteConfigByMonthKey(`${year}${month}`)) return notFoundMeta();
    const basho = bashoLabel(year, month);
    return pageMeta(canonicalPath, `${basho} 番付 | o-sumo`, `${basho}の番付を確認できます。`);
  }

  const hubMatch = canonicalPath.match(/^\/(\d{4})(\d{2})-(torikumi|yotei)\/$/);
  if (hubMatch) {
    const [, year, month, mode] = hubMatch;
    if (!getArchiveRouteConfigByMonthKey(`${year}${month}`)) return notFoundMeta();
    const basho = bashoLabel(year, month);
    const isResult = mode === 'torikumi';
    return pageMeta(
      canonicalPath,
      `${basho} ${isResult ? '取組・星取表' : '取組予定'} | o-sumo`,
      `${basho}の${isResult ? '取組結果と星取表' : '取組予定'}を確認できます。`,
    );
  }

  const dayMatch = canonicalPath.match(/^\/(\d{4})(\d{2})(\d{2})-(torikumi|yotei)\/$/);
  if (dayMatch) {
    const [, year, month, day, mode] = dayMatch;
    const basho = bashoLabel(year, month);
    const isResult = mode === 'torikumi';
    const archiveDay = findArchiveDay(`${year}${month}${day}`, isResult ? 'result' : 'schedule');
    if (!archiveDay) return notFoundMeta();
    const dayLabel = archiveDay.label;
    return pageMeta(
      canonicalPath,
      `${basho} ${dayLabel} ${isResult ? '取組・星取表' : '取組予定'} | o-sumo`,
      `${basho}${dayLabel}の${isResult ? '取組結果と星取表' : '取組予定'}を確認できます。`,
    );
  }

  if (/^\/(gyoji|yobidashi)\/[1-9]\d*\/$/.test(canonicalPath)) {
    const isGyoji = canonicalPath.startsWith('/gyoji/');
    return pageMeta(canonicalPath, `${isGyoji ? '行司' : '呼出'}プロフィール | o-sumo`, `大相撲の${isGyoji ? '行司' : '呼出'}プロフィールを紹介します。`);
  }

  if (/^\/rikishi\/[^/]+\/$/.test(canonicalPath)) {
    return pageMeta(
      canonicalPath,
      '力士プロフィール | o-sumo',
      '大相撲力士のプロフィール、番付、成績を確認できます。',
    );
  }

  return notFoundMeta();
}

